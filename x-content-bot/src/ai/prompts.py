# 모든 콘텐츠 유형 목록
ALL_CONTENT_TYPES = list(CONTENT_TYPE_PROMPTS.keys())


def build_user_prompt(content_type: str, news_summary: str) -> str:
    """콘텐츠 유형과 뉴스 요약을 결합하여 사용자 프롬프트를 생성한다."""
    type_prompt = CONTENT_TYPE_PROMPTS.get(content_type, "")
    if not type_prompt:
        raise ValueError(f"알 수 없는 콘텐츠 유형: {content_type}")

    return f"""{type_prompt}

## 오늘의 뉴스
{news_summary}

위 뉴스 중 가장 적합한 1개를 선택하여 포스트를 작성해주세요.
JSON 형식으로만 응답하세요."""
